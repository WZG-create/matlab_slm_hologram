function catalog = zernike14_catalog()
%ZERNIKE14_CATALOG Return the 14 low-order aberration modes used by the UI.
%
% Coefficients are expressed in waves. Coordinates follow x = r*cos(theta)
% and y = r*sin(theta) on a unit pupil. The ordering mirrors the low-order
% wavefront component set described by the HOLOEYE Pattern Generator manual.

catalog = struct();
catalog.index = (1:14)';
catalog.key = [ ...
    "tilt_x"; "tilt_y"; "defocus"; "astigmatism_45"; "astigmatism_0"; ...
    "trefoil_x"; "trefoil_y"; "coma_x"; "coma_y"; "spherical"; ...
    "secondary_astigmatism_45"; "secondary_astigmatism_0"; ...
    "quadrafoil_x"; "quadrafoil_y"];
catalog.name_zh = [ ...
    "倾斜 X"; "倾斜 Y"; "离焦"; "像散 45°"; "像散 0°"; ...
    "三叶 X"; "三叶 Y"; "彗差 X"; "彗差 Y"; "球差"; ...
    "二级像散 45°"; "二级像散 0°"; "四叶 X"; "四叶 Y"];
catalog.formula = [ ...
    "x"; "y"; "2r²-1"; "2xy"; "x²-y²"; ...
    "3x²y-y³"; "x³-3xy²"; "(3r²-2)x"; "(3r²-2)y"; ...
    "6r⁴-6r²+1"; "(4r²-3)2xy"; "(4r²-3)(x²-y²)"; ...
    "4xy(x²-y²)"; "x⁴-6x²y²+y⁴"];
end
